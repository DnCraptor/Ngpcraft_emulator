def glyph_rows(code: int) -> list[str]:
    """The eight 8-pixel rows of one character, as '#' / ' ' strings.

    The design is seven rows tall and the eighth is left clear, so lines of text
    never touch. The four descenders sit one row lower inside those seven rather
    than reaching into the eighth — the cell is too short to afford both.
    """
    char = chr(code)
    design = GLYPHS_5X7.get(char)
    if design is None:
        return [" " * 8] * 8
    # One column of left bearing, two of right: 5 + 1 + 2 = 8.
    rows = [" " + row + "  " for row in design]
    rows.append(" " * 8)
    assert len(rows) == 8 and all(len(r) == 8 for r in rows), char
    return rows
